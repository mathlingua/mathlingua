/// Parses a non-infix, non-refined command header.
///
/// Command headers consist of a chain, optional head argument groups, optional
/// colon tail parts, and optional parenthesized argument groups.  The contents
/// of header argument groups are forms/declarations because headings describe
/// definition shapes rather than concrete expression references.
pub(super) fn parse_simple_command_header(input: &str) -> Result<CommandHeaderNode, ParseError> {
    let mut rest = input
        .trim()
        .strip_prefix('\\')
        .ok_or_else(|| ParseError::custom("command headers must start with `\\`"))?;
    let (chain_text, remaining) = split_prefix_by_delimiters(rest, &['{', '(', ':']);
    let chain = parse_chain(chain_text)?;
    rest = remaining;

    let (head_args, remaining) = parse_curly_heading_args(rest)?;
    rest = remaining;
    let (tail, remaining) = parse_command_header_tail(rest)?;
    rest = remaining;
    let (paren_args, remaining) = parse_paren_heading_args(rest)?;
    if !remaining.trim().is_empty() {
        return Err(ParseError::custom(
            "unexpected trailing text after command header",
        ));
    }

    Ok(CommandHeaderNode {
        span: span_all(input),
        chain,
        head_args,
        tail,
        paren_args,
    })
}

/// Parses an infix command header delimited by `\.` and `./`.
///
/// Infix headers share most command-tail syntax with ordinary command headers
/// but intentionally omit parenthesized invocation arguments at the end.
pub(super) fn parse_infix_command_header(input: &str) -> Result<InfixCommandHeader, ParseError> {
    let input = input.trim();
    let start = find_top_level_substring(input, "\\.")
        .ok_or_else(|| ParseError::custom("infix command headers must contain `\\.`"))?;
    let left_text = input[..start].trim();
    let (left, left_placeholder) = if left_text.is_empty() {
        (None, false)
    } else {
        let (form, placeholder) = parse_infix_heading_operand(left_text)?;
        (Some(form), placeholder)
    };

    let after_start = &input[start + "\\.".len()..];
    let end = find_top_level_substring(after_start, "./")
        .ok_or_else(|| ParseError::custom("infix command headers must end with `./`"))?;
    let mut rest = &after_start[..end];
    let right_text = after_start[end + "./".len()..].trim();
    let (right, right_placeholder) = if right_text.is_empty() {
        (None, false)
    } else {
        let (form, placeholder) = parse_infix_heading_operand(right_text)?;
        (Some(form), placeholder)
    };

    if left.is_some() != right.is_some() {
        return Err(ParseError::custom(
            "infix command headers must include both left and right operands",
        ));
    }

    let (chain_text, remaining) = split_prefix_by_delimiters(rest, &['{', ':']);
    let chain = parse_chain(chain_text)?;
    rest = remaining;

    let (head_args, remaining) = parse_curly_heading_args(rest)?;
    rest = remaining;
    let (tail, remaining) = parse_command_header_tail(rest)?;
    if !remaining.trim().is_empty() {
        return Err(ParseError::custom(
            "unexpected trailing text after infix command header",
        ));
    }

    Ok(InfixCommandHeader {
        span: span_all(input),
        left,
        left_placeholder,
        chain,
        head_args,
        tail,
        right,
        right_placeholder,
    })
}

/// Parses a spec-infix header delimited by `\:` and `:/`.
///
/// Spec-infix headings define specification operators, so both operands are
/// required and the predicate spelling `?:/` is reserved for use sites.
pub(super) fn parse_infix_spec_header(input: &str) -> Result<InfixSpecHeader, ParseError> {
    let input = input.trim();
    let split = split_infix_spec_statement(input)
        .ok_or_else(|| ParseError::custom("spec-infix headers must contain `\\:`...`:/`"))?;

    if split.predicate {
        return Err(ParseError::custom(
            "spec-infix headers must be declared with `:/`; use `?:/` only in expressions",
        ));
    }
    if split.left.is_empty() || split.right.is_empty() {
        return Err(ParseError::custom(
            "spec-infix headers require both left and right operands",
        ));
    }

    let left = parse_form_or_declaration(split.left)?;
    let (refinement, chain, head_args, tail) = parse_infix_spec_header_body(split.body)?;
    let right = parse_form_or_declaration(split.right)?;

    Ok(InfixSpecHeader {
        span: span_all(input),
        left,
        refinement,
        chain,
        head_args,
        tail,
        right,
    })
}

fn parse_infix_spec_header_body(
    input: &str,
) -> Result<
    (
        Option<InfixSpecHeaderRefinement>,
        Chain,
        Vec<CurlyHeadingArgs>,
        Vec<CommandHeaderTailPart>,
    ),
    ParseError,
> {
    if contains_top_level(input, "::") {
        let refined = parse_refined_command_header(&format!("\\{}", input.trim()))?;
        let RefinedTail::Chain(chain) = refined.refined_tail else {
            return Err(ParseError::custom(
                "refined spec-infix headers must refine a command chain",
            ));
        };
        if !refined.paren_args.is_empty() {
            return Err(ParseError::custom(
                "refined spec-infix headers do not accept parenthesized arguments",
            ));
        }
        return Ok((
            Some(InfixSpecHeaderRefinement {
                prefix_chain: refined.prefix_chain,
                parts: refined.parts,
            }),
            chain,
            refined.head_args,
            refined.tail,
        ));
    }

    let mut rest = input.trim();
    let (chain_text, remaining) = split_prefix_by_delimiters(rest, &['{', ':']);
    let chain = parse_chain(chain_text)?;
    rest = remaining;

    let (head_args, remaining) = parse_curly_heading_args(rest)?;
    rest = remaining;
    let (tail, remaining) = parse_command_header_tail(rest)?;
    if !remaining.trim().is_empty() {
        return Err(ParseError::custom(
            "unexpected trailing text after spec-infix header body",
        ));
    }

    Ok((None, chain, head_args, tail))
}

fn parse_infix_spec_expression_body(input: &str, predicate: bool) -> Result<InfixSpec, ParseError> {
    if contains_top_level(input, "::") {
        let refined = parse_refined_command_expression(&format!("\\{}", input.trim()))?;
        let RefinedTail::Chain(chain) = refined.refined_tail else {
            return Err(ParseError::custom(
                "refined spec-infix expressions must refine a command chain",
            ));
        };
        if !refined.paren_args.is_empty() {
            return Err(ParseError::custom(
                "refined spec-infix expressions do not accept parenthesized arguments",
            ));
        }
        return Ok(InfixSpec {
            span: span_all(input),
            refinement: Some(InfixSpecExpressionRefinement {
                prefix_chain: refined.prefix_chain,
                parts: refined.parts,
            }),
            chain,
            head_args: refined.head_args,
            tail: refined.tail,
            predicate,
        });
    }

    let mut rest = input.trim();
    let (chain_text, remaining) = split_prefix_by_delimiters(rest, &['{', ':']);
    let chain = parse_chain(chain_text)?;
    rest = remaining;

    let (head_args, remaining) = parse_curly_expression_args(rest)?;
    rest = remaining;
    let (tail, remaining) = parse_command_expression_tail(rest)?;
    if !remaining.trim().is_empty() {
        return Err(ParseError::custom(
            "unexpected trailing text after spec-infix expression body",
        ));
    }

    Ok(InfixSpec {
        span: span_all(input),
        refinement: None,
        chain,
        head_args,
        tail,
        predicate,
    })
}

/// Parses a refined command header such as `\(continuous)::function:on{A}:to{B}`.
///
/// The left side lists refinement parts, optionally prefixed by a dotted chain.
/// The right side is parsed as the refined target tail plus the same argument
/// and colon-tail shape used by ordinary command headers.
pub(super) fn parse_refined_command_header(
    input: &str,
) -> Result<RefinedCommandHeader, ParseError> {
    let input = input.trim();
    let after_slash = input
        .strip_prefix('\\')
        .ok_or_else(|| ParseError::custom("refined command headers must start with `\\`"))?;
    let separator = find_top_level_substring(after_slash, "::")
        .ok_or_else(|| ParseError::custom("refined command headers require top-level `::`"))?;
    let left = after_slash[..separator].trim();
    let mut right = after_slash[separator + 2..].trim();

    let open_index = find_first_top_level_char(left, '(')
        .ok_or_else(|| ParseError::custom("expected refined header part list"))?;
    let prefix = left[..open_index].trim();
    let (inside, suffix) = consume_balanced_prefix(&left[open_index..], '(', ')')?;
    if !suffix.trim().is_empty() {
        return Err(ParseError::custom("unexpected trailing text before `::`"));
    }

    let prefix_chain = if prefix.is_empty() {
        None
    } else {
        let chain_text = prefix
            .strip_suffix('.')
            .ok_or_else(|| ParseError::custom("refined header prefix chain must end with `.`"))?;
        Some(parse_chain(chain_text)?)
    };

    let parts = split_top_level(inside, ',')?
        .into_iter()
        .map(parse_refined_header_part)
        .collect::<Result<Vec<_>, _>>()?;
    if parts.is_empty() {
        return Err(ParseError::custom(
            "refined command headers require at least one part",
        ));
    }

    let (refined_tail, remaining) = parse_refined_tail(right)?;
    right = remaining;
    let (head_args, remaining) = parse_curly_heading_args(right)?;
    right = remaining;
    let (tail, remaining) = parse_command_header_tail(right)?;
    right = remaining;
    let (paren_args, remaining) = parse_paren_heading_args(right)?;
    if !remaining.trim().is_empty() {
        return Err(ParseError::custom(
            "unexpected trailing text after refined command header",
        ));
    }

    Ok(RefinedCommandHeader {
        span: span_all(input),
        prefix_chain,
        parts,
        refined_tail,
        head_args,
        tail,
        paren_args,
    })
}

/// Parses one part inside a refined command header part list.
///
/// Each part is a command chain plus optional colon-tail header arguments.  The
/// caller is responsible for splitting the comma-separated part list safely.
pub(super) fn parse_refined_header_part(input: &str) -> Result<RefinedHeaderPart, ParseError> {
    let input = input.trim();
    let (chain_text, rest) = split_prefix_by_delimiters(input, &[':']);
    let chain = parse_chain(chain_text)?;
    let (tail, remaining) = parse_command_header_tail(rest)?;
    if !remaining.trim().is_empty() {
        return Err(ParseError::custom(
            "unexpected trailing text after refined header part",
        ));
    }

    Ok(RefinedHeaderPart {
        span: span_all(input),
        chain,
        tail,
    })
}

/// Parses a refined command expression used at reference sites.
///
/// This mirrors refined command header parsing, but argument groups contain
/// expressions instead of forms because use sites supply concrete values.
pub(super) fn parse_refined_command_expression(
    input: &str,
) -> Result<RefinedCommandExpression, ParseError> {
    let input = input.trim();
    let after_slash = input
        .strip_prefix('\\')
        .ok_or_else(|| ParseError::custom("refined command expressions must start with `\\`"))?;
    let separator = find_top_level_substring(after_slash, "::")
        .ok_or_else(|| ParseError::custom("refined command expressions require top-level `::`"))?;
    let left = after_slash[..separator].trim();
    let mut right = after_slash[separator + 2..].trim();

    let open_index = find_first_top_level_char(left, '(')
        .ok_or_else(|| ParseError::custom("expected refined expression part list"))?;
    let prefix = left[..open_index].trim();
    let (inside, suffix) = consume_balanced_prefix(&left[open_index..], '(', ')')?;
    if !suffix.trim().is_empty() {
        return Err(ParseError::custom("unexpected trailing text before `::`"));
    }

    let prefix_chain = if prefix.is_empty() {
        None
    } else {
        let chain_text = prefix.strip_suffix('.').ok_or_else(|| {
            ParseError::custom("refined expression prefix chain must end with `.`")
        })?;
        Some(parse_chain(chain_text)?)
    };

    let parts = split_top_level(inside, ',')?
        .into_iter()
        .map(parse_refined_expression_part)
        .collect::<Result<Vec<_>, _>>()?;
    if parts.is_empty() {
        return Err(ParseError::custom(
            "refined command expressions require at least one part",
        ));
    }

    let (refined_tail, remaining) = parse_refined_tail(right)?;
    right = remaining;
    let (head_args, remaining) = parse_curly_expression_args(right)?;
    right = remaining;
    let (tail, remaining) = parse_command_expression_tail(right)?;
    right = remaining;
    let (paren_args, remaining) = parse_paren_expression_args(right)?;
    if !remaining.trim().is_empty() {
        return Err(ParseError::custom(
            "unexpected trailing text after refined command expression",
        ));
    }

    Ok(RefinedCommandExpression {
        span: span_all(input),
        prefix_chain,
        parts,
        refined_tail,
        head_args,
        tail,
        paren_args,
    })
}

fn parse_suffixed_command_expression(input: &str) -> Option<Result<Expression, ParseError>> {
    let input = input.trim();
    if !input.starts_with('\\')
        || input.starts_with("\\\\")
        || input.starts_with("\\.")
        || input.starts_with("\\:")
        || contains_top_level(input, "::")
    {
        return None;
    }

    if find_top_level_substring(input, "#using").is_none()
        && find_top_level_substring(input, "#given").is_none()
    {
        return None;
    }

    Some(
        parse_simple_command_expression_with_context(input)
            .map(|command| Expression::new(span_all(input), ExpressionKind::Command(command))),
    )
}

fn parse_simple_command_expression_with_context(
    input: &str,
) -> Result<CommandExpression, ParseError> {
    let input = input.trim();
    let mut rest = input
        .strip_prefix('\\')
        .ok_or_else(|| ParseError::custom("command expressions must start with `\\`"))?;
    let (chain_text, remaining) = split_prefix_by_delimiters(rest, &['{', '(', ':', '#']);
    let chain = parse_chain(chain_text)?;
    rest = remaining;
    let (head_args, remaining) = parse_curly_expression_args(rest)?;
    rest = remaining;
    let (tail, remaining) = parse_command_expression_tail(rest)?;
    rest = remaining;
    let (paren_args, remaining) = parse_paren_expression_args(rest)?;
    rest = remaining;
    let (context, remaining) = parse_command_context_suffix(rest)?;
    if !remaining.trim().is_empty() {
        return Err(ParseError::custom(format!(
            "unexpected trailing text `{}` in command expression",
            remaining.trim()
        )));
    }

    Ok(CommandExpression {
        span: span_all(input),
        chain,
        head_args,
        tail,
        paren_args,
        context,
    })
}

fn parse_command_context_suffix(input: &str) -> Result<(Option<CommandContext>, &str), ParseError> {
    let input = input.trim_start();
    let (kind, rest) = if let Some(rest) = input.strip_prefix("#using") {
        (CommandContextKind::Using, rest)
    } else if let Some(rest) = input.strip_prefix("#given") {
        (CommandContextKind::Given, rest)
    } else {
        return Ok((None, input));
    };

    let rest = rest.trim_start();
    let (inside, remaining) = consume_balanced_prefix(rest, '{', '}')?;
    let arguments = split_top_level(inside, ';')?
        .into_iter()
        .filter(|argument| !argument.trim().is_empty())
        .map(parse_command_context_argument)
        .collect::<Result<Vec<_>, _>>()?;

    Ok((
        Some(CommandContext {
            span: span_all(&input[..input.len() - remaining.len()]),
            kind,
            arguments,
        }),
        remaining,
    ))
}

fn parse_command_context_argument(input: &str) -> Result<CommandContextArgument, ParseError> {
    let input = input.trim();
    if let Some(index) = find_top_level_definition(input) {
        let name = parse_name_token(&input[..index])?;
        let value = parse_expression(&input[index + 2..])?;
        return Ok(CommandContextArgument::Assignment {
            span: span_all(input),
            name,
            value,
        });
    }

    if let Ok(statement) = parse_ordinary_declaration_statement(input) {
        return Ok(CommandContextArgument::Declaration(statement));
    }

    if let Ok(expression) = parse_expression(input) {
        return Ok(CommandContextArgument::Expression(expression));
    }

    Ok(CommandContextArgument::Text(input.to_owned()))
}

/// Parses one part inside a refined command expression part list.
///
/// Expression parts use expression-valued command tails, which lets references
/// provide concrete command arguments while keeping the same chain syntax as
/// refined headers.
pub(super) fn parse_refined_expression_part(
    input: &str,
) -> Result<RefinedExpressionPart, ParseError> {
    let input = input.trim();
    let (chain_text, rest) = split_prefix_by_delimiters(input, &[':']);
    let chain = parse_chain(chain_text)?;
    let (tail, remaining) = parse_command_expression_tail(rest)?;
    if !remaining.trim().is_empty() {
        return Err(ParseError::custom(
            "unexpected trailing text after refined expression part",
        ));
    }

    Ok(RefinedExpressionPart {
        span: span_all(input),
        chain,
        tail,
    })
}

/// Parses the target tail after a refined command's `::` separator.
///
/// The tail can be either a bracketed name, written as `[[name]]`, or a command
/// chain.  The function returns both the parsed tail and the unconsumed suffix
/// so callers can continue parsing argument groups and colon tails.
pub(super) fn parse_refined_tail(input: &str) -> Result<(RefinedTail, &str), ParseError> {
    let input = input.trim_start();
    if let Some(rest) = input.strip_prefix("[[") {
        let end = rest
            .find("]]")
            .ok_or_else(|| ParseError::custom("unterminated refined tail name"))?;
        let name = parse_name_token(&rest[..end])?;
        let consumed = input.len() - rest[end + 2..].len();
        return Ok((
            RefinedTail::Name {
                span: Span::new(0, consumed),
                name,
            },
            &rest[end + 2..],
        ));
    }

    let (chain_text, rest) = split_prefix_by_delimiters(input, &['{', '(', ':']);
    Ok((RefinedTail::Chain(parse_chain(chain_text)?), rest))
}

/// Parses consecutive `{...}` argument groups in a command header.
///
/// Header argument groups contain forms/declarations because command headings
/// define arity and placeholder names, not concrete use-site expressions.
pub(super) fn parse_curly_heading_args(
    mut input: &str,
) -> Result<(Vec<CurlyHeadingArgs>, &str), ParseError> {
    let mut args = Vec::new();
    while input.trim_start().starts_with('{') {
        input = input.trim_start();
        let (inside, rest) = consume_balanced_prefix(input, '{', '}')?;
        let variadic = parse_variadic_parameter(inside)?;
        args.push(CurlyHeadingArgs {
            span: span_all(&input[..input.len() - rest.len()]),
            forms: if variadic.is_some() {
                Vec::new()
            } else {
                parse_form_list(inside)?
            },
            variadic,
        });
        input = rest;
    }

    Ok((args, input))
}

/// Parses the supported variadic header spellings. A variadic parameter must be
/// the only parameter in its curly argument group.
fn parse_variadic_parameter(input: &str) -> Result<Option<VariadicParameter>, ParseError> {
    let input = input.trim();
    if !input.contains("...") {
        return Ok(None);
    }
    if input.contains(',') {
        return Err(ParseError::custom(
            "a variadic parameter must be the only parameter in its `{...}` argument group",
        ));
    }

    if !input.contains('[') {
        let split = input
            .find("...")
            .ok_or_else(|| ParseError::custom("invalid variadic parameter"))?;
        let name = parse_name_token(input[..split].trim())?;
        let suffix = input[split + 3..].trim();
        let length = if suffix.is_empty() {
            None
        } else {
            Some(parse_name_token(suffix)?)
        };
        return Ok(Some(VariadicParameter {
            span: span_all(input),
            name,
            length,
            index: None,
            start: 0,
        }));
    }

    let open = input
        .find('[')
        .ok_or_else(|| ParseError::custom("invalid variadic parameter"))?;
    let name = parse_name_token(input[..open].trim())?;
    let bracketed = input[open..]
        .strip_prefix('[')
        .and_then(|value| value.strip_suffix(']'))
        .ok_or_else(|| {
            ParseError::custom("variadic parameter index must be enclosed in `[...]`")
        })?;
    let assignment = find_top_level_definition(bracketed).ok_or_else(|| {
        ParseError::custom("variadic parameter indices require `i_ := 0...` or `i_ := 1...`")
    })?;
    let index = parse_placeholder(bracketed[..assignment].trim())?.name;
    let range = bracketed[assignment + 2..].trim();
    let (start, length) = if let Some(length) = range.strip_prefix("0...") {
        (0, length)
    } else if let Some(length) = range.strip_prefix("1...") {
        (1, length)
    } else {
        return Err(ParseError::custom(
            "variadic parameter indices must start at 0 or 1",
        ));
    };
    let length = if length.trim().is_empty() {
        None
    } else {
        Some(parse_name_token(length.trim())?)
    };
    Ok(Some(VariadicParameter {
        span: span_all(input),
        name,
        length,
        index: Some(index),
        start,
    }))
}

/// Parses consecutive `(...)` argument groups in a command header.
///
/// Parenthesized header groups describe invocation arguments for callable
/// definitions.  They are optional at use sites but still part of the definition
/// shape when present in a heading.
pub(super) fn parse_paren_heading_args(
    mut input: &str,
) -> Result<(Vec<ParenHeadingArgs>, &str), ParseError> {
    let mut args = Vec::new();
    while input.trim_start().starts_with('(') {
        input = input.trim_start();
        let (inside, rest) = consume_balanced_prefix(input, '(', ')')?;
        args.push(ParenHeadingArgs {
            span: span_all(&input[..input.len() - rest.len()]),
            forms: parse_paren_heading_form_list(inside)?,
        });
        input = rest;
    }

    Ok((args, input))
}

/// Parses the parameters inside a command heading's trailing `(...)` group.
///
/// Ordinary forms use bare names, but callable headings may spell their input
/// parameters as placeholders to mirror a function declaration, for example
/// `\natural.succ(n_)`. A standalone placeholder has the same header shape as
/// its bare name, so normalize `n_` to the existing name-form representation.
fn parse_paren_heading_form_list(input: &str) -> Result<Vec<FormOrDeclaration>, ParseError> {
    let forms = split_top_level(input, ',')?
        .into_iter()
        .map(parse_heading_form_or_placeholder)
        .collect::<Result<Vec<_>, _>>()?;
    if forms.is_empty() {
        return Err(ParseError::custom("expected at least one form"));
    }
    Ok(forms)
}

/// Parses one command-heading parameter, normalizing standalone placeholder
/// spelling to the same named parameter shape used for ordinary forms.
///
/// This is shared by callable `(...)` parameters and infix operands so
/// `\sin(x_)` and `n_ \.natural.+./ m_` bind parameters consistently.
fn parse_heading_form_or_placeholder(input: &str) -> Result<FormOrDeclaration, ParseError> {
    match parse_form_or_declaration(input) {
        Ok(form) => Ok(form),
        Err(form_error) => match parse_placeholder(input) {
            Ok(placeholder) => Ok(FormOrDeclaration::new(
                placeholder.span,
                FormOrDeclarationKind::Name(placeholder.name),
            )),
            Err(_) => Err(form_error),
        },
    }
}

/// Parses an infix command-heading operand and records whether it used
/// placeholder spelling. Placeholder operands are callable parameters, like
/// parameters in a trailing `(...)` heading group, rather than independent
/// values that require a `when:` declaration.
fn parse_infix_heading_operand(input: &str) -> Result<(FormOrDeclaration, bool), ParseError> {
    if let Ok(placeholder) = parse_placeholder(input) {
        return Ok((
            FormOrDeclaration::new(
                placeholder.span,
                FormOrDeclarationKind::Name(placeholder.name),
            ),
            true,
        ));
    }
    parse_form_or_declaration(input).map(|form| (form, false))
}

/// Parses colon-prefixed tail parts for command headers.
///
/// A tail part must include at least one `{...}` group, which prevents bare
/// punctuation like `:to` from being accepted without the argument shape that
/// gives the part semantic content.
pub(super) fn parse_command_header_tail(
    mut input: &str,
) -> Result<(Vec<CommandHeaderTailPart>, &str), ParseError> {
    let mut parts = Vec::new();
    loop {
        input = input.trim_start();
        if !input.starts_with(':') || input.starts_with("::") {
            break;
        }

        let (optional, tail_body) = if let Some(rest) = input.strip_prefix(":?") {
            (true, rest)
        } else {
            (false, &input[1..])
        };
        let (chain_text, rest) = split_prefix_by_delimiters(tail_body, &['{']);
        let chain = parse_chain(chain_text)?;
        let (args, remaining) = parse_curly_heading_args(rest)?;
        if args.is_empty() {
            return Err(ParseError::custom(
                "header tail parts require at least one `{...}` argument list",
            ));
        }

        parts.push(CommandHeaderTailPart {
            span: span_all(&input[..input.len() - remaining.len()]),
            chain,
            args,
            optional,
        });
        input = remaining;
    }

    Ok((parts, input))
}

/// Parses consecutive `{...}` argument groups in a command expression.
///
/// Expression argument groups carry concrete expression ASTs and therefore use
/// the expression list parser rather than the form/declaration list parser used
/// for command headers.
pub(super) fn parse_curly_expression_args(
    mut input: &str,
) -> Result<(Vec<CurlyExpressionArgs>, &str), ParseError> {
    let mut args = Vec::new();
    while input.trim_start().starts_with('{') {
        input = input.trim_start();
        let (inside, rest) = consume_balanced_prefix(input, '{', '}')?;
        let group = &input[..input.len() - rest.len()];
        // Collection-literal sugar: `\foo{x_ : ...}` == `\foo{{x_ : ...}}`.
        let expressions = match parse_collection_literal_argument(group, inside) {
            Some(set) => vec![set],
            None => parse_expression_list(inside)?,
        };
        args.push(CurlyExpressionArgs {
            span: span_all(group),
            expressions,
        });
        input = rest;
    }

    Ok((args, input))
}

/// If a `{...}` command-argument group (`group` includes the braces, `inside`
/// does not) is a brace-less collection literal, parses it as a single set
/// expression. Returns `None` when the content is not a set-builder.
fn parse_collection_literal_argument(group: &str, inside: &str) -> Option<Expression> {
    find_set_comprehension_colon(inside)?;
    parse_set_expression(group).ok()
}

/// Parses consecutive `(...)` argument groups in a command expression.
///
/// These groups represent invocation at a use site.  Semantic checking later
/// verifies whether the referenced definition allows the supplied parenthesized
/// arity.
pub(super) fn parse_paren_expression_args(
    mut input: &str,
) -> Result<(Vec<ParenExpressionArgs>, &str), ParseError> {
    let mut args = Vec::new();
    while input.trim_start().starts_with('(') {
        input = input.trim_start();
        let (inside, rest) = consume_balanced_prefix(input, '(', ')')?;
        args.push(ParenExpressionArgs {
            span: span_all(&input[..input.len() - rest.len()]),
            expressions: parse_expression_list(inside)?,
        });
        input = rest;
    }

    Ok((args, input))
}

/// Parses colon-prefixed tail parts for command expressions.
///
/// Each tail part must provide at least one `{...}` expression argument group so
/// reference signatures retain the same required shape as their definitions.
pub(super) fn parse_command_expression_tail(
    mut input: &str,
) -> Result<(Vec<CommandExpressionTailPart>, &str), ParseError> {
    let mut parts = Vec::new();
    loop {
        input = input.trim_start();
        if !input.starts_with(':') || input.starts_with("::") {
            break;
        }

        let (optional, tail_body) = if let Some(rest) = input.strip_prefix(":?") {
            (true, rest)
        } else {
            (false, &input[1..])
        };
        let (chain_text, rest) = split_prefix_by_delimiters(tail_body, &['{']);
        let chain = parse_chain(chain_text)?;
        let (args, remaining) = parse_curly_expression_args(rest)?;
        if args.is_empty() {
            return Err(ParseError::custom(
                "command tail parts require at least one `{...}` argument list",
            ));
        }

        parts.push(CommandExpressionTailPart {
            span: span_all(&input[..input.len() - remaining.len()]),
            chain,
            args,
            optional,
        });
        input = remaining;
    }

    Ok((parts, input))
}

/// Parses consecutive `{...}` argument groups for a builtin command.
///
/// Builtin clauses use semicolon-separated arguments because each argument may
/// itself contain comma-separated declaration syntax, such as
/// `x, y is \real; n is \natural`.
fn parse_builtin_command_args(
    mut input: &str,
) -> Result<(Vec<BuiltinCommandArgs>, &str), ParseError> {
    let mut args = Vec::new();
    while input.trim_start().starts_with('{') {
        input = input.trim_start();
        let (inside, rest) = consume_balanced_prefix(input, '{', '}')?;
        let arguments = split_top_level(inside, ';')?
            .into_iter()
            .map(|argument| BuiltinCommandArgument::Text(argument.to_owned()))
            .collect::<Vec<_>>();
        args.push(BuiltinCommandArgs {
            span: span_all(&input[..input.len() - rest.len()]),
            arguments,
        });
        input = rest;
    }

    Ok((args, input))
}

/// Parses colon-prefixed tail parts for builtin command expressions.
fn parse_builtin_command_tail(
    mut input: &str,
) -> Result<(Vec<BuiltinCommandTailPart>, &str), ParseError> {
    let mut parts = Vec::new();
    loop {
        input = input.trim_start();
        if !input.starts_with(':') || input.starts_with("::") {
            break;
        }

        if input.starts_with(":?") {
            return Err(ParseError::custom(
                "builtin command tail parts do not support optional `:?` syntax",
            ));
        }

        let tail_body = &input[1..];
        let (chain_text, rest) = split_prefix_by_delimiters(tail_body, &['{']);
        let chain = parse_chain(chain_text)?;
        let (args, remaining) = parse_builtin_command_args(rest)?;
        if args.is_empty() {
            return Err(ParseError::custom(
                "builtin command tail parts require at least one `{...}` argument list",
            ));
        }

        parts.push(BuiltinCommandTailPart {
            span: span_all(&input[..input.len() - remaining.len()]),
            chain,
            args,
        });
        input = remaining;
    }

    Ok((parts, input))
}

fn parse_builtin_command_expression(input: &str) -> Option<Result<Expression, ParseError>> {
    let input = input.trim();
    let body = input.strip_prefix("\\\\")?;

    Some((|| {
        let (chain_text, rest) = split_prefix_by_delimiters(body, &['{', ':']);
        let chain = parse_chain(chain_text)?;
        let (head_args, rest) = parse_builtin_command_args(rest)?;
        let (tail, rest) = parse_builtin_command_tail(rest)?;
        if !rest.trim().is_empty() {
            return Err(ParseError::custom(format!(
                "unexpected trailing text `{}` in builtin command",
                rest.trim()
            )));
        }

        Ok(Expression::new(
            span_all(input),
            ExpressionKind::BuiltinCommand(BuiltinCommandExpression {
                span: span_all(input),
                chain,
                head_args,
                tail,
            }),
        ))
    })())
}

